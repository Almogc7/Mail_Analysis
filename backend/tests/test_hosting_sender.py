"""Machine-provisioned sender identity + brand claim, and registrable-domain mismatch checks."""
import pytest

from app.auth_check import run_auth_check
from app.auth_check.spoofing import (
    check_identity_mismatch,
    looks_autogenerated_local_part,
    looks_like_machine_label,
)
from app.contracts.email import EmailAddress, ParsedEmail
from app.parser import parse_email_file
from app.scoring import run_scoring
from tests.eval import FIXTURES


def _email(display, address, subject=None, **kw):
    domain = address.split("@")[1]
    return ParsedEmail(
        source_format="eml",
        from_=EmailAddress(display_name=display, address=address, domain=domain),
        subject=subject,
        raw_size_bytes=1,
        **kw,
    )


def _hosting(parsed):
    return check_identity_mismatch(parsed)["hosting_fqdn_sender"]


@pytest.mark.parametrize("label", ["vh319", "s12", "srv7", "vps12345", "mail3", "host", "cpanel", "mx2"])
def test_machine_labels(label):
    assert looks_like_machine_label(label)


@pytest.mark.parametrize("label", ["www", "news", "mail", "mailer", "bakery", "billing", "abcde12", "smtp"])
def test_not_machine_labels(label):
    assert not looks_like_machine_label(label)


@pytest.mark.parametrize("local", ["vnz73mailr", "a1b2c3d4", "j3d9k2", "user12x"])
def test_autogenerated_local_parts(local):
    assert looks_autogenerated_local_part(local)


@pytest.mark.parametrize("local", ["john2024", "alice", "support", "noreply", "a1b2", "john.smith", "first_last9"])
def test_human_or_role_local_parts_are_not_autogenerated(local):
    assert not looks_autogenerated_local_part(local)


def test_kvish6_fixture_gets_the_finding_with_both_indicators():
    path = FIXTURES / "malicious" / "kvish6_invoice_phish.eml"
    parsed = parse_email_file(path.read_bytes(), path.name)
    h = _hosting(parsed)
    assert h["suspected"] and h["brand"] == "kvish6" and h["brand_source"] == "display_name"
    assert len(h["indicators"]) == 2
    finding = next(f for f in run_auth_check(parsed).findings if f.title == "Machine-provisioned sender claiming a brand")
    assert finding.severity == "medium" and finding.weight == 15.0
    assert "server-style hostname ('vh319' under 'sweb.ru')" in finding.description
    assert "auto-generated" in finding.description


def test_brand_only_in_the_subject_still_counts():
    parsed = _email("Customer Care", "vnz73mailr@vh319.hosting.example.net", subject="[EXTERNAL] Your PayPal receipt")
    h = _hosting(parsed)
    assert h["suspected"] and h["brand"] == "paypal" and h["brand_source"] == "subject"


def test_gateway_tag_in_subject_does_not_manufacture_a_brand():
    parsed = _email("Customer Care", "vnz73mailr@vh319.hosting.example.net", subject="[Caution: Suspicious Email!] hello")
    assert not _hosting(parsed)["suspected"]


def test_machine_sender_without_a_brand_claim_is_not_flagged():
    # contact forms, cron mail, small-business hosting are common and benign
    parsed = _email("Bakery website", "bakeryuser@host12.hosting.example.net", subject="New contact-form message")
    h = _hosting(parsed)
    assert not h["suspected"] and h["indicators"]  # indicators are recorded, just not scored


def test_brand_claim_from_a_normal_looking_sender_is_not_this_finding():
    parsed = _email("PayPal Support", "support@mailer.example.org", subject="Notice")
    assert not _hosting(parsed)["suspected"]  # (the display-name finding covers this case)


def test_machine_sender_that_really_belongs_to_the_brand_is_not_flagged():
    parsed = _email("PayPal Support", "svc1a2b3c@srv12.paypal.com", subject="Receipt")
    assert not _hosting(parsed)["suspected"]


def test_finding_is_medium_and_never_a_floor_by_itself():
    parsed = _email("Customer Care", "vnz73mailr@vh319.hosting.example.net", subject="Your PayPal receipt")
    result = run_auth_check(parsed)
    assert {f.title: f.severity for f in result.findings}["Machine-provisioned sender claiming a brand"] == "medium"
    from app.contracts.findings import ModuleResult

    quiet = [ModuleResult(module=m, status="ok", findings=[], raw_data={}) for m in ("enrichment", "content_analysis")]
    outcome = run_scoring([result, *quiet])
    assert not any(o.rule == "auth_check_floor" for o in outcome.breakdown.applied_overrides)


# ---- registrable-domain mismatch (benign ESP subdomains no longer look like spoofing) ----------

def _mismatch(from_domain, other_domain, key):
    parsed = ParsedEmail(
        source_format="eml",
        from_=EmailAddress(address=f"a@{from_domain}", domain=from_domain),
        return_path=EmailAddress(address=f"b@{other_domain}", domain=other_domain),
        reply_to=[EmailAddress(address=f"b@{other_domain}", domain=other_domain)],
        raw_size_bytes=1,
    )
    return check_identity_mismatch(parsed)[key]["mismatch"]


@pytest.mark.parametrize("key", ["from_return_path_mismatch", "from_reply_to_mismatch"])
@pytest.mark.parametrize(
    "from_domain,other,expected",
    [
        ("mail.example.com", "bounce.mail.example.com", False),
        ("example.com", "bounce.example.com", False),
        ("news.example.co.uk", "mail.example.co.uk", False),
        ("example.com", "other-domain.example.net", True),
        ("example.co.uk", "attacker.co.uk", True),
    ],
)
def test_mismatch_is_judged_on_registrable_domains(key, from_domain, other, expected):
    assert _mismatch(from_domain, other, key) is expected
