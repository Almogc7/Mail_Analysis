import json
from functools import lru_cache
from pathlib import Path
from typing import Any

from app.contracts.email import EmailAddress, ParsedEmail
from app.shared.brands import KNOWN_BRANDS
from app.parser.preprocess import clean_subject
from app.shared.matching import domain_matches_any, find_brand_matches, registrable_domain


FREEMAIL_FILE = Path(__file__).resolve().parents[1] / "shared" / "freemail_domains.json"


@lru_cache(maxsize=1)
def load_freemail_domains() -> frozenset[str]:
    """Free consumer mailbox providers, from a config file (not hardcoded)."""
    data = json.loads(FREEMAIL_FILE.read_text(encoding="utf-8"))
    domains = data.get("domains") if isinstance(data, dict) else None
    if not isinstance(domains, list) or not all(isinstance(d, str) and d.strip() for d in domains):
        raise ValueError(f'{FREEMAIL_FILE.name} must be {{"domains": ["example.com", ...]}}')
    return frozenset(d.strip().strip(".").lower() for d in domains)


def is_freemail(domain: str | None) -> bool:
    if not domain:
        return False
    domain = domain.strip(".").lower()
    return any(domain == d or domain.endswith("." + d) for d in load_freemail_domains())


def _domain_mismatch(a: EmailAddress | None, b: EmailAddress | None) -> dict[str, Any]:
    """Compared on REGISTRABLE domains: 'bounce.mail.example.com' vs 'mail.example.com' is the
    same organisation (what DMARC calls relaxed alignment), not a mismatch."""
    domain_a = a.domain if a else None
    domain_b = b.domain if b else None
    if domain_a is None or domain_b is None:
        return {"mismatch": False, "domain_a": domain_a, "domain_b": domain_b}
    reg_a, reg_b = registrable_domain(domain_a) or domain_a, registrable_domain(domain_b) or domain_b
    return {"mismatch": reg_a != reg_b, "domain_a": domain_a, "domain_b": domain_b}


def _check_display_name_spoofing(from_addr: EmailAddress) -> dict[str, Any]:
    """Token-based (see app.shared.matching). `suspected` -- which drives the SUSPICIOUS
    floor -- requires an EXACT whole-token brand match (plain, homoglyph or leet-folded)
    AND a sender registrable domain outside that brand's legitimate domains. A fuzzy-only
    (edit distance 1) look-alike sets `fuzzy_suspected` instead: a medium finding, no floor."""
    actual_domain = from_addr.domain
    result: dict[str, Any] = {
        "suspected": False,
        "fuzzy_suspected": False,
        "match_type": None,
        "normalization": None,
        "claimed_brand": None,
        "actual_domain": actual_domain,
        "actual_registrable_domain": registrable_domain(actual_domain),
        "match_score": 0,
    }
    matches = find_brand_matches(from_addr.display_name, KNOWN_BRANDS)
    # Only brands the sender domain does NOT belong to are impersonation candidates; prefer
    # exact over fuzzy.
    candidates = [m for m in matches if not domain_matches_any(actual_domain, KNOWN_BRANDS[m.brand])]
    candidates.sort(key=lambda m: m.kind != "exact")
    if not candidates:
        legit = matches[0] if matches else None
        if legit:
            result.update(match_type=legit.kind, claimed_brand=legit.brand, normalization=legit.via,
                          match_score=100.0 if legit.kind == "exact" else 90.0)
        return result
    top = candidates[0]
    result.update(
        match_type=top.kind,
        normalization=top.via,
        claimed_brand=top.brand,
        match_score=100.0 if top.kind == "exact" else 90.0,
        suspected=top.kind == "exact",
        fuzzy_suspected=top.kind == "fuzzy",
    )
    return result


# Bare service labels (mail, smtp, mx, web) are deliberately NOT here: "mail.example.com" is the most
# common benign newsletter subdomain. Numbered forms ("mail3", "mx2") still count via the
# letters-then-digits rule in looks_like_machine_label.
_MACHINE_WORDS = {"server", "srv", "host", "vps", "node", "cpanel", "vh", "ns"}


def _runs(text: str) -> list[str]:
    """Run-length kinds of a string: 'vnz73mailr' -> ['a', 'd', 'a'] (a=letters, d=digits, x=other)."""
    kinds: list[str] = []
    for ch in text:
        kind = "a" if ch.isalpha() else "d" if ch.isdigit() else "x"
        if not kinds or kinds[-1] != kind:
            kinds.append(kind)
    return kinds


def looks_like_machine_label(label: str) -> bool:
    """A server-ish hostname label: 1-4 letters then digits ('vh319', 's12', 'srv7') or a
    machine word with optional digits ('mail3', 'host')."""
    label = label.lower()
    if label.rstrip("0123456789") in _MACHINE_WORDS:
        return True
    head = label.rstrip("0123456789")
    digits = label[len(head):]
    return head.isalpha() and 1 <= len(head) <= 4 and 1 <= len(digits) <= 5


def looks_autogenerated_local_part(local: str) -> bool:
    """Control-panel / auto-provisioned mailbox names ('vnz73mailr'): alphanumeric, 6+ chars, and
    letters-digits-letters interleaving. 'john2024' (letters then digits) does not qualify."""
    local = local.lower()
    runs = _runs(local)
    return len(local) >= 6 and local.isalnum() and len(runs) >= 3 and "d" in runs and "a" in runs


def _check_hosting_fqdn_sender(parsed: ParsedEmail) -> dict[str, Any]:
    """MEDIUM signal: the From identity looks machine-provisioned (a server FQDN as the domain,
    and/or an auto-generated mailbox) while the display name or subject claims a brand the sender
    domain does not belong to. A brand claim is required -- machine-looking senders alone are
    common and benign (contact forms, cron mail)."""
    from_addr = parsed.from_
    result: dict[str, Any] = {"suspected": False, "indicators": [], "brand": None, "brand_source": None}
    domain = (from_addr.domain or "").lower()
    reg = registrable_domain(domain)
    indicators: list[str] = []
    if reg and domain != reg:
        leftmost = domain[: -len(reg)].rstrip(".").split(".")[0]
        if looks_like_machine_label(leftmost):
            indicators.append(f"From domain is a server-style hostname ('{leftmost}' under '{reg}')")
    local = (from_addr.address or "").rsplit("@", 1)[0]
    if local and looks_autogenerated_local_part(local):
        indicators.append("From mailbox name looks auto-generated")
    if not indicators:
        return result

    subject, _ = clean_subject(parsed.subject)
    for source, text in (("display_name", from_addr.display_name), ("subject", subject)):
        for match in find_brand_matches(text, KNOWN_BRANDS):
            if match.kind == "exact" and not domain_matches_any(domain, KNOWN_BRANDS[match.brand]):
                result.update(suspected=True, indicators=indicators, brand=match.brand, brand_source=source)
                return result
    result["indicators"] = indicators
    return result


def _check_local_submission(parsed: ParsedEmail) -> dict[str, Any]:
    """S2: the message ENTERED the mail system by local submission (Exim 'with local', Postfix 'from userid') and not by
    authenticated SMTP. The first hop is the LAST Received header. Common for a site's own contact-form mail, so it is
    a weak, one-family signal that only matters with corroboration."""
    result: dict[str, Any] = {"suspected": False, "hop": None}
    if not parsed.received_chain:
        return result
    first = parsed.received_chain[-1]
    if first.is_local_submission and not first.authenticated:
        result.update(suspected=True, hop={"protocol": first.protocol, "by_host": first.by_host, "envelope_from": first.envelope_from})
    return result


def _check_freemail_brand(parsed: ParsedEmail, display_name_spoofing: dict[str, Any]) -> dict[str, Any]:
    """S3: a free consumer mailbox whose display name carries a brand it does not belong to."""
    freemail = is_freemail(parsed.from_.domain)
    return {
        "suspected": bool(freemail and display_name_spoofing.get("suspected")),
        "freemail": freemail,
        "claimed_brand": display_name_spoofing.get("claimed_brand") if freemail else None,
        "actual_domain": parsed.from_.domain,
    }


def check_identity_mismatch(parsed: ParsedEmail) -> dict[str, Any]:
    from_return_path = _domain_mismatch(parsed.from_, parsed.return_path)
    from_reply_to = _domain_mismatch(
        parsed.from_, parsed.reply_to[0] if parsed.reply_to else None
    )
    display_name_spoofing = _check_display_name_spoofing(parsed.from_)

    return {
        "from_return_path_mismatch": {
            "mismatch": from_return_path["mismatch"],
            "from_domain": from_return_path["domain_a"],
            "return_path_domain": from_return_path["domain_b"],
        },
        "from_reply_to_mismatch": {
            "mismatch": from_reply_to["mismatch"],
            "from_domain": from_reply_to["domain_a"],
            "reply_to_domain": from_reply_to["domain_b"],
        },
        "display_name_spoofing": display_name_spoofing,
        "hosting_fqdn_sender": _check_hosting_fqdn_sender(parsed),
        "local_submission": _check_local_submission(parsed),
        "freemail_brand": _check_freemail_brand(parsed, display_name_spoofing),
    }
